// ── 생성자 / 소멸자 ──────────────────────────────────────────────
Board::Board() {
    winMap_   = newwin(MAP_SIZE + 2, MAP_SIZE * 2 + 2, 0, 0);
    winBoard_ = newwin(MAP_SIZE + 2, 26, 0, MAP_SIZE * 2 + 3);
}

Board::~Board() {
    delwin(winMap_);
    delwin(winBoard_);
}

// ── 스테이지 로드 ────────────────────────────────────────────────
void Board::loadStage(int stage) {
    for (int i = 0; i < MAP_SIZE; i++)
        for (int j = 0; j < MAP_SIZE; j++) {
            baseMap_[i][j] = STAGE_MAPS[stage][i][j];
            map_[i][j]     = STAGE_MAPS[stage][i][j];
        }
}

// ── 셀 접근자 ────────────────────────────────────────────────────
void Board::setCell(int y, int x, int val) {
    map_[y][x] = val;
}

int Board::getCell(int y, int x) const {
    return map_[y][x];
}

int Board::getBase(int y, int x) const {
    return baseMap_[y][x];
}

WINDOW* Board::getWinMap() const {
    return winMap_;
}

// ── 맵 렌더링 ────────────────────────────────────────────────────
void Board::draw() const {
    werase(winMap_);
    box(winMap_, 0, 0);

    for (int i = 0; i < MAP_SIZE; i++) {
        for (int j = 0; j < MAP_SIZE; j++) {
            wmove(winMap_, i + 1, j * 2 + 1);
            switch (map_[i][j]) {
                case CELL_EMPTY:
                    wprintw(winMap_, "  ");
                    break;
                case CELL_WALL:
                    wattron(winMap_, COLOR_PAIR(2));
                    wprintw(winMap_, "##");
                    wattroff(winMap_, COLOR_PAIR(2));
                    break;
                case CELL_IMMUNE:
                    wattron(winMap_, COLOR_PAIR(3));
                    wprintw(winMap_, "%%");
                    wattroff(winMap_, COLOR_PAIR(3));
                    break;
                case CELL_HEAD:
                    wattron(winMap_, COLOR_PAIR(4));
                    wprintw(winMap_, "HH");
                    wattroff(winMap_, COLOR_PAIR(4));
                    break;
                case CELL_BODY:
                    wattron(winMap_, COLOR_PAIR(5));
                    wprintw(winMap_, "OO");
                    wattroff(winMap_, COLOR_PAIR(5));
                    break;
                case CELL_GROWTH:
                    wattron(winMap_, COLOR_PAIR(6));
                    wprintw(winMap_, "++");
                    wattroff(winMap_, COLOR_PAIR(6));
                    break;
                case CELL_POISON:
                    wattron(winMap_, COLOR_PAIR(7));
                    wprintw(winMap_, "--");
                    wattroff(winMap_, COLOR_PAIR(7));
                    break;
                case CELL_GATE:
                    wattron(winMap_, COLOR_PAIR(8));
                    wprintw(winMap_, "GG");
                    wattroff(winMap_, COLOR_PAIR(8));
                    break;
                case CELL_SPEED:
                    wattron(winMap_, COLOR_PAIR(9));
                    wprintw(winMap_, "**");
                    wattroff(winMap_, COLOR_PAIR(9));
                    break;
                default:
                    wprintw(winMap_, "  ");
                    break;
            }
        }
    }
    wrefresh(winMap_);
}

// ── 점수판 렌더링 ────────────────────────────────────────────────
void Board::drawScoreBoard(int stage, int elapsedSec,
                           int curLen, int maxLen,
                           int growth, int poison, int gate,
                           const Mission& m,
                           int curScore, int highScore) const {
    werase(winBoard_);
    box(winBoard_, 0, 0);

    mvwprintw(winBoard_,  1, 2, "[ Score Board ]");
    mvwprintw(winBoard_,  2, 2, "Stage  : %d",    stage + 1);
    mvwprintw(winBoard_,  3, 2, "Time   : %ds",   elapsedSec);
    mvwprintw(winBoard_,  4, 2, "Score  : %d",    curScore);
    mvwprintw(winBoard_,  5, 2, "Best   : %d",    highScore);

    mvwprintw(winBoard_,  7, 2, "B: %d / %d",     curLen, maxLen);
    mvwprintw(winBoard_,  8, 2, "+: %d",           growth);
    mvwprintw(winBoard_,  9, 2, "-: %d",           poison);
    mvwprintw(winBoard_, 10, 2, "G: %d",           gate);

    mvwprintw(winBoard_, 12, 2, "[ Mission ]");
    mvwprintw(winBoard_, 13, 2, "B>=%2d : %s", m.targetLength,
              curLen >= m.targetLength ? "v" : "x");
    mvwprintw(winBoard_, 14, 2, "+>=%2d : %s", m.targetGrowth,
              growth  >= m.targetGrowth ? "v" : "x");
    mvwprintw(winBoard_, 15, 2, "->=%2d : %s", m.targetPoison,
              poison  >= m.targetPoison ? "v" : "x");
    mvwprintw(winBoard_, 16, 2, "G>=%2d : %s", m.targetGate,
              gate    >= m.targetGate   ? "v" : "x");

    wrefresh(winBoard_);
}

// ── 메시지 표시 ──────────────────────────────────────────────────
void Board::showMessage(const std::string& msg) const {
    const int y = MAP_SIZE / 2 + 1;
    int x = (MAP_SIZE * 2 - (int)msg.size()) / 2 + 1;
    if (x < 1) x = 1;
    mvwprintw(winMap_, y, x, "%s", msg.c_str());
    wrefresh(winMap_);
    napms(1800);
}
